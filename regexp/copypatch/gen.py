#!/usr/bin/env python3
"""Turn a freestanding ELF64 object of stencils into a C header.

usage: gen.py stencils.o aarch64|x86_64 > stencils_<arch>.h

The header holds, per stencil function, its machine code and a table of holes
(offset, relocation kind, symbol, addend).  Relocation kinds are renamed to the
ISA-independent R_* names copypatch.c knows how to apply.
"""

import struct
import sys
from pathlib import Path

RELOCS = {
    "x86_64": {1: "ABS64", 2: "PC32", 4: "PC32"},
    "aarch64": {
        257: "ABS64",
        263: "MOVW0", 264: "MOVW0",
        265: "MOVW1", 266: "MOVW1",
        267: "MOVW2", 268: "MOVW2",
        269: "MOVW3",
        282: "BRANCH26", 283: "BRANCH26",
    },
}  # fmt: skip
MACHINE = {"x86_64": 62, "aarch64": 183}
SHT_SYMTAB, SHT_RELA, SHF_ALLOC = 2, 4, 2
TEXT = (".text.", ".ltext.")  # x86-64's large code model uses .ltext


def cstr(buf: bytes, at: int) -> str:
    return buf[at : buf.index(0, at)].decode()


def need(ok: object, msg: str) -> None:
    if not ok:
        sys.exit(f"gen.py: {msg}")


def main(path: str, arch: str) -> None:
    elf = Path(path).read_bytes()
    need(elf[:6] == b"\x7fELF\x02\x01", "not a little-endian ELF64 object")
    machine = struct.unpack_from("<H", elf, 0x12)[0]
    need(machine == MACHINE[arch], f"object is not {arch}")

    shoff = struct.unpack_from("<Q", elf, 0x28)[0]
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", elf, 0x3A)
    sh = [
        struct.unpack_from("<IIQQQQIIQQ", elf, shoff + i * shentsize)
        for i in range(shnum)
    ]  # name type flags addr offset size link info align entsize
    names = [cstr(elf, sh[shstrndx][4] + s[0]) for s in sh]

    stencils: dict[int, str] = {}
    for i, (s, name) in enumerate(zip(sh, names)):
        need(
            name.startswith(TEXT) or not (s[2] & SHF_ALLOC and s[5]),
            f"{name}: stencils may not use data, only holes",
        )
        if name.startswith(TEXT):
            stencils[i] = name.split(".", 2)[2]

    symtab = next(s for s in sh if s[1] == SHT_SYMTAB)
    strtab = sh[symtab[6]][4]
    syms = [
        struct.unpack_from("<IBBHQQ", elf, symtab[4] + off)
        for off in range(0, symtab[5], 24)
    ]  # name info other shndx value size

    # a stencil is copied from its section's first byte, so its symbol must sit there
    entries = {(s[3], cstr(elf, strtab + s[0])) for s in syms if s[4] == 0}
    for i, name in stencils.items():
        need((i, name) in entries, f"{name}: not at the start of its section")

    out = [f"/* Generated by gen.py from stencils.c for {arch}.  Do not edit. */\n"]
    max_code = max_holes = 0
    for i, name in stencils.items():
        code = elf[sh[i][4] : sh[i][4] + sh[i][5]]
        holes = []
        for r in sh:
            if r[1] != SHT_RELA or r[7] != i:
                continue
            for off in range(r[4], r[4] + r[5], 24):
                at, info, addend = struct.unpack_from("<QQq", elf, off)
                kind = RELOCS[arch].get(info & 0xFFFFFFFF)
                sym = syms[info >> 32]
                need(kind, f"{name}: unsupported relocation {info & 0xFFFFFFFF}")
                need(sym[3] == 0, f"{name}: relocation against a defined symbol")
                holes.append((at, kind, cstr(elf, strtab + sym[0]), addend))
        max_code, max_holes = max(max_code, len(code)), max(max_holes, len(holes))

        rows = (code[j : j + 12] for j in range(0, len(code), 12))
        body = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in row) for row in rows)
        out.append(f"static const uint8_t {name}_code[] = {{\n{body},\n}};\n")
        if holes:
            rows = ",\n".join(
                f"    {{0x{at:X}, R_{kind}, H_{sym}, {addend}}}"
                for at, kind, sym, addend in sorted(holes)
            )
            out.append(f"static const struct hole {name}_holes[] = {{\n{rows},\n}};\n")
            table = f"{name}_holes, sizeof {name}_holes / sizeof *{name}_holes"
        else:
            table = "0, 0"
        out.append(
            f"static const struct stencil stencil_{name} = "
            f"{{{name}_code, sizeof {name}_code, {table}}};\n"
        )
    out.append(f"enum {{ MAX_CODE = {max_code}, MAX_HOLES = {max_holes} }};")
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:])
