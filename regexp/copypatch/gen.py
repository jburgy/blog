#!/usr/bin/env python3
"""Turn a freestanding ELF64 object of stencils into a C header.

usage: gen.py stencils.o aarch64|x86_64 > stencils_<arch>.h

The header holds, per stencil function, its machine code and a table of holes
(offset, relocation kind, symbol, addend).  Relocation kinds are renamed to the
ISA-independent R_* names copypatch.c knows how to apply.

The object is read with llvm-readobj's JSON output ($LLVM_READOBJ, default
llvm-readobj), the way CPython's own copy-and-patch build does.
"""

import json
import os
import shutil
import subprocess
import sys

READOBJ = os.environ.get("LLVM_READOBJ", "llvm-readobj")
RELOCS = {
    "x86_64": {
        "R_X86_64_64": "ABS64",
        "R_X86_64_PC32": "PC32",
        "R_X86_64_PLT32": "PC32",
    },
    "aarch64": {
        "R_AARCH64_ABS64": "ABS64",
        "R_AARCH64_MOVW_UABS_G0": "MOVW0", "R_AARCH64_MOVW_UABS_G0_NC": "MOVW0",
        "R_AARCH64_MOVW_UABS_G1": "MOVW1", "R_AARCH64_MOVW_UABS_G1_NC": "MOVW1",
        "R_AARCH64_MOVW_UABS_G2": "MOVW2", "R_AARCH64_MOVW_UABS_G2_NC": "MOVW2",
        "R_AARCH64_MOVW_UABS_G3": "MOVW3",
        "R_AARCH64_JUMP26": "BRANCH26", "R_AARCH64_CALL26": "BRANCH26",
    },
}  # fmt: skip
TEXT = (".text.", ".ltext.")  # x86-64's large code model uses .ltext


def need(ok: object, msg: str) -> None:
    if not ok:
        sys.exit(f"gen.py: {msg}")


def main(path: str, arch: str) -> None:
    need(shutil.which(READOBJ), f"{READOBJ} not found; set $LLVM_READOBJ")
    flags = ["--sections", "--section-data", "--relocations", "--symbols"]
    argv = [READOBJ, "--elf-output-style=JSON", *flags, path]
    run = subprocess.run(argv, capture_output=True, text=True, check=True)
    obj = json.loads(run.stdout)[0]
    summary = obj["FileSummary"]
    need(
        summary["Format"].startswith("elf64-") and summary["Arch"] == arch,
        f"object is not {arch} ELF64",
    )

    sections = {s["Section"]["Index"]: s["Section"] for s in obj["Sections"]}
    stencils: dict[int, str] = {}
    for i, s in sections.items():
        name = s["Name"]["Name"]
        alloc = "SHF_ALLOC" in {f["Name"] for f in s["Flags"]["Flags"]}
        need(
            name.startswith(TEXT) or not (alloc and s["Size"]),
            f"{name}: stencils may not use data, only holes",
        )
        if name.startswith(TEXT):
            stencils[i] = name.split(".", 2)[2]

    symbols = [s["Symbol"] for s in obj["Symbols"]]
    # a stencil is copied from its section's first byte, so its symbol must sit there
    entries = {
        (s["Section"]["Value"], s["Name"]["Name"]) for s in symbols if not s["Value"]
    }
    for i, name in stencils.items():
        need((i, name) in entries, f"{name}: not at the start of its section")
    undefined = {s["Name"]["Name"] for s in symbols if s["Section"]["Value"] == 0}
    # a .rela section's Info is the index of the section it patches
    relocs = {
        sections[r["SectionIndex"]]["Info"]: [x["Relocation"] for x in r["Relocs"]]
        for r in obj["Relocations"]
    }

    out = [f"/* Generated by gen.py from stencils.c for {arch}.  Do not edit. */\n"]
    max_code = max_holes = 0
    for i, name in stencils.items():
        code = bytes(sections[i]["SectionData"]["Bytes"])
        holes = []
        for r in relocs.get(i, []):
            kind = RELOCS[arch].get(r["Type"]["Name"])
            sym = r["Symbol"]["Name"]
            need(kind, f"{name}: unsupported relocation {r['Type']['Name']}")
            need(sym in undefined, f"{name}: relocation against a defined symbol")
            holes.append((r["Offset"], kind, sym, r["Addend"]))
        max_code, max_holes = max(max_code, len(code)), max(max_holes, len(holes))

        rows = (code[j : j + 12] for j in range(0, len(code), 12))
        body = ",\n".join("    " + ", ".join(f"0x{b:02X}" for b in row) for row in rows)
        out.append(f"static const uint8_t {name}_code[] = {{\n{body},\n}};\n")
        if holes:
            rows = ",\n".join(
                f"    {{0x{at:X}, R_{kind}, H_{sym}, {addend}}}"
                for at, kind, sym, addend in sorted(holes)
            )
            out.append(f"static const struct hole {name}_holes[] = {{\n{rows},\n}};\n")
            table = f"{name}_holes, sizeof {name}_holes / sizeof *{name}_holes"
        else:
            table = "0, 0"
        out.append(
            f"static const struct stencil stencil_{name} = "
            f"{{{name}_code, sizeof {name}_code, {table}}};\n"
        )
    out.append(f"enum {{ MAX_CODE = {max_code}, MAX_HOLES = {max_holes} }};")
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:])
